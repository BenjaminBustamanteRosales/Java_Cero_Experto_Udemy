public class ReglasNombresVariables {
    public static void main(String[] args) {

        String nombreCompleto = "Juan Carlos";
        System.out.println("nombreCompleto = " + nombreCompleto);

        String $nombreCompleto = "Juan Carlos 2";
        System.out.println("$nombreCompleto = " + $nombreCompleto);

        String _nombreCompleto = "Juan Carlos 3";
        System.out.println("_nombreCompleto = " + _nombreCompleto);

        boolean esCasado = true;
        boolean isCasado = true;
        System.out.println("isCasado = " + isCasado);

        boolean hasSaldo = true;
        System.out.println("hasSaldo = " + hasSaldo);


    }
}
